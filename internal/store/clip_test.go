package store

import "testing"

// Байтовая обрезка на кириллице врёт вдвое и рубит букву пополам: в интерфейсе
// это ромб с вопросительным знаком вместо последней буквы.
func TestОбрезкаСчитаетСимволыАНеБайты(t *testing.T) {
	текст := "Отвечай коротко, по-русски и только по делу"

	got := Clip(текст, 20)
	runes := []rune(got)
	if len(runes) != 21 { // двадцать букв плюс многоточие
		t.Fatalf("получили %d символов: %q", len(runes), got)
	}
	if runes[len(runes)-1] != '…' {
		t.Errorf("нет многоточия: %q", got)
	}
	for _, r := range got {
		if r == '\uFFFD' {
			t.Fatalf("буква разрублена пополам: %q", got)
		}
	}
	if короткий := Clip("да", 20); короткий != "да" {
		t.Errorf("короткую строку тронули: %q", короткий)
	}
	if пусто := Clip("", 5); пусто != "" {
		t.Errorf("пустую строку тронули: %q", пусто)
	}
}
